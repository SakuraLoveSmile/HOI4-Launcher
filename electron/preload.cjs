const { contextBridge, ipcRenderer } = require("electron");

// Electron's Error serialization discards custom fields. Known diagnostics use
// an explicit data envelope; the public API still rejects with an Error.
async function invoke(...args) {
  const result = await ipcRenderer.invoke(...args);
  if (
    result &&
    result.__ironcladDiagnosticError === 1 &&
    typeof result.message === "string"
  ) {
    const error = new Error(result.message);
    error.diagnostic = result.diagnostic;
    if (typeof result.code === "string") error.code = result.code;
    throw error;
  }
  return result;
}

